//! Dynamic SQL built from string literals and bound values only.

use std::fmt::Display;

use sqlx::{
    Database, Encode, FromRow, SqlStr, Type,
    query::{Query, QueryAs, QueryScalar},
    query_builder,
};

/// Builds a query at runtime, for example a search with optional filters,
/// without ever pasting a runtime string into the SQL.
///
/// SQL fragments must be `&'static str` (string literals), and values go
/// through [`push_bind`](Self::push_bind), so they are sent separately
/// from the SQL and can't change its meaning:
///
/// ```
/// # #[cfg(feature = "sqlite")] {
/// use ironhold_db::QueryBuilder;
/// use sqlx::Sqlite;
///
/// let author = Some(7_i64);
/// let title = "Hello' OR '1'='1";
///
/// let mut query = QueryBuilder::<Sqlite>::new("SELECT id FROM posts WHERE 1 = 1");
/// if let Some(author) = author {
///     query.push(" AND author_id = ").push_bind(author);
/// }
/// query.push(" AND title = ").push_bind(title);
/// assert_eq!(
///     query.sql().as_str(),
///     "SELECT id FROM posts WHERE 1 = 1 AND author_id = ? AND title = ?"
/// );
/// # }
/// ```
///
/// A runtime string doesn't compile:
///
/// ```compile_fail
/// # use ironhold_db::QueryBuilder;
/// # use sqlx::Sqlite;
/// let email = String::from("nobody' OR '1'='1");
/// let query = QueryBuilder::<Sqlite>::new(format!("SELECT * FROM users WHERE email = '{email}'"));
/// ```
///
/// ```compile_fail
/// # use ironhold_db::QueryBuilder;
/// # use sqlx::Sqlite;
/// let column = String::from("title; DROP TABLE posts");
/// let mut query = QueryBuilder::<Sqlite>::new("SELECT * FROM posts ORDER BY ");
/// query.push(column);
/// ```
///
/// When SQL really has to come from a runtime value (a column name picked
/// from a fixed list, say), use [`push_unchecked`](Self::push_unchecked),
/// which stands out in review.
///
/// sqlx's own `sqlx::QueryBuilder` accepts any string; apps generated by
/// `ironhold new` forbid it with a Clippy rule in `clippy.toml`.
pub struct QueryBuilder<DB: Database> {
    inner: sqlx::QueryBuilder<DB>,
}

impl<DB: Database> QueryBuilder<DB>
where
    DB::Arguments: Default,
{
    /// Starts a query with `sql`, a string literal.
    #[expect(
        clippy::disallowed_methods,
        reason = "the one place sqlx's builder is used, with literal SQL only"
    )]
    pub fn new(sql: &'static str) -> Self {
        Self {
            inner: sqlx::QueryBuilder::new(sql),
        }
    }
}

impl<DB: Database> QueryBuilder<DB> {
    /// Appends `sql`, a string literal.
    #[expect(
        clippy::disallowed_methods,
        reason = "only literal SQL reaches sqlx's builder here"
    )]
    pub fn push(&mut self, sql: &'static str) -> &mut Self {
        self.inner.push(sql);
        self
    }

    /// Appends a placeholder (`?` or `$N`) and binds `value` to it.
    pub fn push_bind<'t, T>(&mut self, value: T) -> &mut Self
    where
        T: Encode<'t, DB> + Type<DB>,
    {
        self.inner.push_bind(value);
        self
    }

    /// Appends SQL built at runtime, without any check. Anything a user
    /// controls that ends up here is SQL injection. Prefer
    /// [`push`](Self::push) and [`push_bind`](Self::push_bind); use this
    /// only for values picked from a fixed list in code.
    #[expect(
        clippy::disallowed_methods,
        reason = "the explicit, clearly named opt-out"
    )]
    pub fn push_unchecked(&mut self, sql: impl Display) -> &mut Self {
        self.inner.push(sql);
        self
    }

    /// Starts a list whose items are separated by `separator`, for
    /// example `", "` inside `IN (...)`.
    pub fn separated(&mut self, separator: &'static str) -> Separated<'_, DB> {
        Separated {
            inner: self.inner.separated(separator),
        }
    }

    /// Appends `VALUES (..), (..)` with one row per item, for inserting
    /// many rows at once. `push_row` adds each row's values.
    pub fn push_values<I, F>(&mut self, rows: I, mut push_row: F) -> &mut Self
    where
        I: IntoIterator,
        F: FnMut(Separated<'_, DB>, I::Item),
    {
        self.inner
            .push_values(rows, |inner, row| push_row(Separated { inner }, row));
        self
    }

    /// The query, ready to run. See `sqlx::QueryBuilder::build`.
    pub fn build(&mut self) -> Query<'_, DB, DB::Arguments> {
        self.inner.build()
    }

    /// The query, returning rows as `T`.
    pub fn build_query_as<'q, T: FromRow<'q, DB::Row>>(
        &'q mut self,
    ) -> QueryAs<'q, DB, T, DB::Arguments> {
        self.inner.build_query_as()
    }

    /// The query, returning the first column as `T`.
    pub fn build_query_scalar<'q, T>(&'q mut self) -> QueryScalar<'q, DB, T, DB::Arguments>
    where
        (T,): for<'r> FromRow<'r, DB::Row>,
    {
        self.inner.build_query_scalar()
    }

    /// Goes back to just the SQL passed to [`new`](Self::new), so the
    /// builder can be reused.
    pub fn reset(&mut self) -> &mut Self {
        self.inner.reset();
        self
    }

    /// The SQL built so far.
    pub fn sql(&self) -> SqlStr {
        self.inner.sql()
    }
}

/// A list inside a [`QueryBuilder`], from
/// [`separated`](QueryBuilder::separated) or
/// [`push_values`](QueryBuilder::push_values).
pub struct Separated<'qb, DB: Database> {
    inner: query_builder::Separated<'qb, DB, &'static str>,
}

impl<DB: Database> Separated<'_, DB> {
    /// Appends the separator (except before the first item), then `sql`.
    #[expect(
        clippy::disallowed_methods,
        reason = "only literal SQL reaches sqlx's builder here"
    )]
    pub fn push(&mut self, sql: &'static str) -> &mut Self {
        self.inner.push(sql);
        self
    }

    /// Appends `sql` without a separator.
    #[expect(
        clippy::disallowed_methods,
        reason = "only literal SQL reaches sqlx's builder here"
    )]
    pub fn push_unseparated(&mut self, sql: &'static str) -> &mut Self {
        self.inner.push_unseparated(sql);
        self
    }

    /// Appends the separator (except before the first item), then a bound
    /// value.
    pub fn push_bind<'t, T>(&mut self, value: T) -> &mut Self
    where
        T: Encode<'t, DB> + Type<DB>,
    {
        self.inner.push_bind(value);
        self
    }

    /// Appends a bound value without a separator.
    pub fn push_bind_unseparated<'t, T>(&mut self, value: T) -> &mut Self
    where
        T: Encode<'t, DB> + Type<DB>,
    {
        self.inner.push_bind_unseparated(value);
        self
    }
}
